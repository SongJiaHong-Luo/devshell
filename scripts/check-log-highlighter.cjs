const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')
const exportsObject = {}
const source = fs.readFileSync(path.join(__dirname, '../src/renderer/src/lib/log-parser.ts'), 'utf8')
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exportsObject })
const { createLogHighlighter, DEFAULT_LOG_COLORS } = exportsObject
const highlight = createLogHighlighter(DEFAULT_LOG_COLORS)
assert.match(highlight('java.lang.RuntimeException: broken\n'), /\x1b\[31m/)
assert.match(highlight('    at example.run(Test.java:1)\n'), /\x1b\[31m/)
assert.equal(highlight('\nnormal prompt$ '), '\nnormal prompt$ ')
const split = createLogHighlighter(DEFAULT_LOG_COLORS)
split('RuntimeExcep')
assert.match(split('tion: failure\n'), /\x1b\[31m/)
assert.match(split('    at next frame\n'), /\x1b\[31m/)
assert.equal(createLogHighlighter([])('SELECT * FROM table\n'), 'SELECT * FROM table\n')
assert.equal(highlight('\x1b[33mremote color\x1b[0m\n'), '\x1b[33mremote color\x1b[0m\n')
console.log('Log highlighting regression checks passed')
