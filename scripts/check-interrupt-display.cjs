const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const vm = require('node:vm')
const ts = require('typescript')
const exportsObject = {}
const source = fs.readFileSync(path.join(__dirname, '../src/renderer/src/lib/interrupt-display.ts'), 'utf8')
vm.runInNewContext(ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exportsObject })
const display = exportsObject.createInterruptDisplay()
assert.equal(display.format('^C[prompt]'), '^C[prompt]')
display.arm()
assert.equal(display.format('^C[prompt]'), '^C\r\n[prompt]')
display.arm()
assert.equal(display.format('^C\r\n[prompt]'), '^C\r\n[prompt]')
display.arm()
assert.equal(display.format('^'), '^')
assert.equal(display.format('C'), 'C')
assert.equal(display.format('[prompt]'), '\r\n[prompt]')
display.arm()
display.format('^C')
assert.equal(display.format('\r\n[prompt]'), '\r\n[prompt]')
console.log('Interrupt display regression checks passed')
